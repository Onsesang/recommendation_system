FMT = lambda v: "—" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.4f}"


def md_table(frame, columns=None, floats=4):
    frame = frame[columns] if columns else frame
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    rule = "|" + "|".join("---" for _ in frame.columns) + "|"
    lines = [header, rule]
    for _, row in frame.iterrows():
        cells = []
        for value in row:
            if isinstance(value, float):
                cells.append("—" if np.isnan(value) else f"{value:.{floats}f}")
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


