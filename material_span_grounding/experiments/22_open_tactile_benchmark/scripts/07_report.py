        block = contrasts.get(key)
        if not block or block.get("delta") is None:
            return (f"{subject} is ahead of {comparator} on the point estimate; a paired "
                    "test for this pair is not available.")
        delta, low, high = block["delta"], block["ci_low"], block["ci_high"]
        if block.get("excludes_zero"):
            return (f"paired bootstrap over evaluation units puts {subject} "
                    f"**{delta:+.4f}** macro AUROC ahead of {comparator}, "
                    f"95 % CI [{low:+.4f}, {high:+.4f}] — **the interval excludes zero**.")
        return (f"paired bootstrap puts the gap at **{delta:+.4f}** macro AUROC, "
                f"95 % CI [{low:+.4f}, {high:+.4f}] — **the interval contains zero, so the "
                f"ordering between {subject} and {comparator} is not established**.")

