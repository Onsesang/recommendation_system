def md_table(frame, floats=4):
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    rule = "|" + "|".join("---" for _ in frame.columns) + "|"
    lines = [header, rule]
    for _, row in frame.iterrows():
        cells = []
        for value in row:
            if isinstance(value, (float, np.floating)):
                cells.append("—" if np.isnan(value) else f"{value:.{floats}f}")
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def with_ci(frame, tag="vs_category_only"):
    frame = frame.copy()
    frame[f"ΔNDCG {tag} [95% CI]"] = [
        f"{r[f'dNDCG_{tag}']:+.4f} [{r[f'dNDCG_{tag}_ci_low']:+.4f}, {r[f'dNDCG_{tag}_ci_high']:+.4f}]"
        + ("" if (r[f'dNDCG_{tag}_ci_low'] > 0 or r[f'dNDCG_{tag}_ci_high'] < 0) else "  ns")
        for _, r in frame.iterrows()]
    return frame


def main() -> int:
    main_frame = pd.read_csv(R.RESULTS / "retrieval_main.csv")
    same = pd.read_csv(R.RESULTS / "retrieval_same_category.csv")
    per_query = pd.read_csv(R.RESULTS / "retrieval_per_query.csv")
